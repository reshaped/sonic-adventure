static struct event_path ev008d_light_path = {511, ev008d_light_points};

static struct task *ev008d_light = NULL;
/* the white fade that ends the event */
static struct task *ev008d_fade = NULL;

void ev008d_script(int phase)
{
    switch (phase) {
    case EVENT_LOAD:
        break;
    case EVENT_PLAY:
        event_reset_player(0);
        event_sound_init(1);
        event_camera_take();
        event_pads_off();
        event_take_control();
        stream_request_music(MUSIC_TICAL);
        event_set_pos(event_get_player(0), 7418.0F, -2192.0F, 1316.0F);
        event_set_ang(event_get_player(0), 0, 0x4000, 0);
        event_wait(1);
        ev008d_light =
            event_light_create(event_get_player(0)->work->pos.x + 12.703F,
                               event_get_player(0)->work->pos.y + 19.99F,
                               event_get_player(0)->work->pos.z + 12.31F);
        event_set_flags(ev008d_light, EVENT_IGNORE_GROUND);
        event_camera_set_pos(EVENT_EASE_SMOOTH, 0,
                             event_get_player(0)->work->pos.x + 22.46F,
                             event_get_player(0)->work->pos.y + 11.4F,
                             event_get_player(0)->work->pos.z + 0.71F);
        event_camera_set_ang(EVENT_EASE_SMOOTH, 0,
                             event_get_player(0)->work->ang.x - 0x0800,
                             0x3f00 - event_get_player(0)->work->ang.y,
                             event_get_player(0)->work->ang.z);
        event_camera_set_pos(EVENT_EASE_SMOOTH, 400,
                             event_get_player(0)->work->pos.x + 40.312F,
                             event_get_player(0)->work->pos.y + 19.03F,
                             event_get_player(0)->work->pos.z + 0.852F);
        event_play_path(ev008d_light, &ev008d_light_path, 3.0F,
                        EVENT_FROM_HERE);
        event_wait(80);
        event_look_at_task(event_get_player(0), ev008d_light, 0.0F, 0.0F, 0.0F);
        event_wait(100);
        event_sound_start(0, SE_TIKAL_CHIME, 88);
        ev008d_fade = event_fade_create(1.0F / 60.0F, 0.0F, 1.0F, 1.0F, 1.0F);
        event_wait(90);
        event_look_clear(event_get_player(0));
        break;
    case EVENT_END:
        event_sound_stop_all();
        event_reset_player(0);
        EVENT_KILL(ev008d_fade);
        event_clear_paths(ev008d_light);
        EVENT_KILL(ev008d_light);
        event_camera_release();
        event_pads_on();
        break;
    case EVENT_UNLOAD:
        break;
    }
}


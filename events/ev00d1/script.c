static const struct event_pad_recording ev00d1_walk = {
    ev00d1_walk_keys, sizeof(ev00d1_walk_keys) / sizeof(ev00d1_walk_keys[0])};

void ev00d1_script(int phase)
{
    switch (phase) {
    case EVENT_LOAD:
        break;
    case EVENT_PLAY:
        event_reset_player(0);
        event_camera_take();
        event_pads_off();
        event_take_control();
        stream_request_music(MUSIC_S_SQUARE);
        event_set_pos(event_get_player(0), 67.0F, 0.8F, 1452.13F);
        event_set_ang(event_get_player(0), 0, 0x1400, 0);
        event_camera_set_pos(EVENT_EASE_SMOOTH, 0, 91.0F, 40.03F, 1490.67F);
        event_camera_set_ang(EVENT_EASE_SMOOTH, 0, 0x0800, 0x1500, 0);
        event_camera_set_pos(EVENT_EASE_LINEAR, 60, 117.93F, 33.71F, 1538.2F);
        event_wait(60);
        event_camera_set_pos(EVENT_EASE_LINEAR, 120, 114.48F, 33.19F, 1532.12F);
        event_camera_set_ang(EVENT_EASE_SMOOTH, 120, 0xf900, 0x1500, 0);
        event_clear_motions(event_get_player(0));
        event_play_pad(0, &ev00d1_walk);
        event_camera_follow(event_get_player(0));
        event_talk_stop(event_get_player(0));
        event_voice_play(1816);
        event_message_show(TEXT_1);
        event_wait(30);
        event_message_clear();
        event_voice_wait();
        event_wait(20);
        event_voice_play(1817);
        event_message_show(TEXT_2);
        event_wait(90);
        event_voice_wait();
        event_message_clear();
        event_wait(80);
        event_camera_follow_clear();
        event_camera_set_ang(EVENT_EASE_SMOOTH, 120, 0xf800, 0x1800, 0);
        event_camera_set_pos(EVENT_EASE_SMOOTH, 120, 99.194F, 22.656F,
                             1513.755F);
        event_talk_stop(event_get_player(0));
        event_voice_play(1818);
        event_message_show(TEXT_3);
        event_wait(240);
        event_message_clear();
        event_message_close();
        break;
    case EVENT_END:
        event_camera_release();
        event_pads_on();
        event_set_pos(event_get_player(0), 78.388F, 0.0F, 1467.228F);
        event_set_ang(event_get_player(0), 0, 0x0adc, 0);
        event_reset_player(0);
        break;
    case EVENT_UNLOAD:
        break;
    }
}


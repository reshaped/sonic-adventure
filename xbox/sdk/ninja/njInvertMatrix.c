Bool(njInvertMatrix)(NJS_MATRIX *m)
{
    Float det = (njDetMatrix)(m);
    Float inverse;

    if (det == 0.0F) {
        union {
            Uint32 bits;
            Float value;
        } fill = {0x7f7fc99e};
        Float filled[16];
        int k;

        for (k = 0; k < 16; k++) {
            filled[k] = fill.value;
        }
        if (m == NULL) {
            sh4_xmtrx_set(filled);
        } else {
            for (k = 0; k < 16; k++) {
                ((Float *)m)[k] = filled[k];
            }
        }
        return FALSE;
    }
    inverse = 1.0F / det;
    if (m == NULL) {
        Float xf[16];
        Float xf_out[16];
        int k;

        sh4_xmtrx_get(xf);
        for (k = 0; k < 16; k++) {
            xf_out[k] = xf[k];
        }
        invert_current(xf, xf_out, inverse);
        sh4_xmtrx_set(xf_out);
    } else {
        invert_memory((Float *)m, inverse);
    }
    return TRUE;
}

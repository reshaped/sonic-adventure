/* vector and point math, angle lookups, color conversion and memory fills.
 * make pc compiles this in place of src/system/math.src, whose comments give
 * each function's arithmetic. across means in the x-z plane.
 *
 * each function runs math.src's operations on its operands in math.src's
 * order. where math.src runs FIPR, FSRRA, FSCA or FTRV, the C runs the
 * port's models of them (xbox/include/sh4.h), whose last bits needn't
 * match the console's. FTRC saturates on the SH-4, so ftrc does too.
 *
 * math.src holds, ahead of its first function, the addresses of eight of
 * Ninja's and Shinobi's calls, which nothing reads. the C keeps none.
 *
 * each definition names its function in parentheses, so that no macro of
 * its name could expand */
#include <ninja.h>
#include <sg_xpt.h>

#include "system/math.h"
#include "xbox/include/sh4.h"

/* a quarter and a half of a turn */
#define QUARTER 0x4000
#define HALF 0x8000

/* FTRC: f truncated toward 0, saturated to Sint32's range as the SH-4's
 * FTRC saturates. a NaN gives what the SH-4 gives a positive overflow */
static Sint32 ftrc(Float f)
{
    if (f >= 2147483648.0F || f != f) {
        return 0x7fffffff;
    }
    if (f < -2147483648.0F) {
        return (Sint32)0x80000000;
    }
    return (Sint32)f;
}

/* NOLINTBEGIN(readability-identifier-length) */
Float angle_sin_over_abs_cos(Angle ang)
{
    Float sine;
    Float cosine;

    _builtin_fsca(ang, &sine, &cosine);
    return sine * _builtin_fsrra(cosine * cosine);
}

/* FIPR FV4,FV0: b is the first operand. math.src's also multiplies the FR7
 * its caller left by 0, where this multiplies 0 by 0 */
Float vector_inner_product(NJS_VECTOR *a, NJS_VECTOR *b)
{
    return sh4_fipr(b->x, b->y, b->z, 0.0F, a->x, a->y, a->z, 0.0F);
}

/* FIPR FV4,FV0 of (b.x, 0, b.z, 0) and (a.x, 0, a.z, 0): b first. math.src's
 * FIPR also multiplies the zeros in FR1 and FR3 by the FR5 and FR7 its
 * caller left, where this multiplies 0 by 0 */
Float(vector_inner_product_across)(NJS_VECTOR *a, NJS_VECTOR *b)
{
    return sh4_fipr(b->x, 0.0F, b->z, 0.0F, a->x, 0.0F, a->z, 0.0F);
}

/* z first, then y, then x, each one FIPR FV0,FV4 of two of a's parts, the
 * second negated, and two of b's, a's first. math.src's also multiplies
 * the FR6 and FR7 it finds by 0, where this multiplies 0 by 0. out must be
 * neither a nor b */
void vector_outer_product(NJS_VECTOR *a, NJS_VECTOR *b, NJS_VECTOR *out)
{
    out->z = sh4_fipr(a->x, -a->y, 0.0F, 0.0F, b->y, b->x, 0.0F, 0.0F);
    out->y = sh4_fipr(a->z, -a->x, 0.0F, 0.0F, b->x, b->z, 0.0F, 0.0F);
    out->x = sh4_fipr(a->y, -a->z, 0.0F, 0.0F, b->z, b->y, 0.0F, 0.0F);
}

Float vector_magnitude(NJS_VECTOR *vector)
{
    return __builtin_sqrtf(vector_magnitude_squared(vector));
}

Float(vector_magnitude_across)(NJS_VECTOR *vector)
{
    return __builtin_sqrtf(sh4_fipr_self(vector->x, 0.0F, vector->z, 0.0F));
}

Float vector_magnitude_squared(NJS_VECTOR *vector)
{
    return sh4_fipr_self(vector->x, vector->y, vector->z, 0.0F);
}

Float vector_magnitude_squared_across(NJS_VECTOR *vector)
{
    return sh4_fipr_self(vector->x, 0.0F, vector->z, 0.0F);
}

/* out may be vector: vector is read whole first */
Float vector_unit(NJS_VECTOR *vector, NJS_VECTOR *out)
{
    Float x = vector->x;
    Float y = vector->y;
    Float z = vector->z;
    Float scale = _builtin_fsrra(sh4_fipr_self(x, y, z, 0.0F));

    out->x = x * scale;
    out->y = y * scale;
    out->z = z * scale;
    return scale;
}

/* out's x and z, and not its y, which math.src leaves */
Float(vector_unit_across)(NJS_VECTOR *vector, NJS_VECTOR *out)
{
    Float x = vector->x;
    Float z = vector->z;
    Float scale = _builtin_fsrra(sh4_fipr_self(x, 0.0F, z, 0.0F));

    out->x = x * scale;
    out->z = z * scale;
    return scale;
}

/* the reciprocals of a's and b's lengths, their product, then a . b, by
 * FIPR FV4,FV8: a is the first operand */
Float vector_cosine(NJS_VECTOR *a, NJS_VECTOR *b)
{
    Float scale = _builtin_fsrra(sh4_fipr_self(a->x, a->y, a->z, 0.0F));

    scale *= _builtin_fsrra(sh4_fipr_self(b->x, b->y, b->z, 0.0F));
    return scale * sh4_fipr(a->x, a->y, a->z, 0.0F, b->x, b->y, b->z, 0.0F);
}


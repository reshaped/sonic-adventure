/* the angle for value, from -1 to 1, in the 513 entries whose middle entry
 * middle points to: value times 256, truncated toward 0, picks an entry n,
 * and the result adds to it the step to entry n + 1, times the fraction the
 * truncation dropped, truncated toward 0 */
static Angle angle_from_table(Float value, const Sint16 *middle)
{
    Float step = 256.0F * value;
    Sint32 entry = ftrc(step);
    Sint32 angle = middle[entry];

    step -= (Float)entry;
    return angle + ftrc((Float)(middle[entry + 1] - angle) * step);
}

Angle angle_arc_sin(Float sine)
{
    return angle_from_table(sine, asin_table + 256);
}

Angle angle_arc_cos(Float cosine)
{
    return angle_from_table(cosine, acos_table + 256);
}

/* (x, y, 0, 1) by FTRV XMTRX where matrix is null, y stored first; else a
 * FIPR FV0,FV4 of it with (m[0], m[4], 0, m[12]) for x, then with (m[1],
 * m[5], 0, m[13]) for y. math.src never loads FR6, which the point's 0
 * meets: here it is 0 */
void(point_calc_xy)(NJS_MATRIX *matrix, NJS_POINT3 *point, Float *out)
{
    Float v[4];

    v[0] = point->x;
    v[1] = point->y;
    v[2] = 0.0F;
    v[3] = 1.0F;
    if (matrix == NULL) {
        sh4_xmtrx_ftrv(v, v);
        out[1] = v[1];
        out[0] = v[0];
        return;
    }
    {
        const Float *m = (const Float *)matrix;

        out[0] = sh4_fipr(v[0], v[1], v[2], v[3], m[0], m[4], 0.0F, m[12]);
        out[1] = sh4_fipr(v[0], v[1], v[2], v[3], m[1], m[5], 0.0F, m[13]);
    }
}

/* b, g, r, then a, from argb's end */
void color_to_argb(Uint32 color, NJS_ARGB *argb)
{
    argb->b = (Float)(Sint32)(color & 0xff);
    argb->g = (Float)(Sint32)(color >> 8 & 0xff);
    argb->r = (Float)(Sint32)(color >> 16 & 0xff);
    argb->a = (Float)(Sint32)(color >> 24);
}

/* the channels are ORed unmasked, as math.src ORs them */
Uint32 color_from_argb(NJS_ARGB *argb)
{
    Uint32 color = (Uint32)ftrc(argb->a) << 24;

    color |= (Uint32)ftrc(argb->r) << 16;
    color |= (Uint32)ftrc(argb->g) << 8;
    return color | (Uint32)ftrc(argb->b);
}

/* a hair under 1/255, as math.src's H'3B808080 */
static Float per_255(void)
{
    union {
        Uint32 bits;
        Float value;
    } per = {0x3b808080};

    return per.value;
}

/* one channel's product: each byte times per_255, their product held to 1,
 * times 255 and rounded */
static Uint32 channel_multiply(Uint32 color, Uint32 by)
{
    Float scale = per_255();
    Float product = (Float)(Sint32)(color & 0xff) * scale;

    product *= (Float)(Sint32)(by & 0xff) * scale;
    if (!(1.0F > product)) {
        product = 1.0F;
    }
    return (Uint32)ftrc(product * 255.0F + 0.5F);
}

Uint32 color_multiply(Uint32 color, Uint32 by)
{
    Uint32 product = channel_multiply(color, by);

    product |= channel_multiply(color >> 8, by >> 8) << 8;
    product |= channel_multiply(color >> 16, by >> 16) << 16;
    return product | channel_multiply(color >> 24, by >> 24) << 24;
}

void color_to_argb_unit(Uint32 color, NJS_ARGB *argb)
{
    Float scale = per_255();

    argb->b = (Float)(Sint32)(color & 0xff) * scale;
    argb->g = (Float)(Sint32)(color >> 8 & 0xff) * scale;
    argb->r = (Float)(Sint32)(color >> 16 & 0xff) * scale;
    argb->a = (Float)(Sint32)(color >> 24) * scale;
}

/* math.src's FMAC rounds once, where the product and the sum here round
 * apart: a channel just under a half can round the other way */
Uint32 color_from_argb_unit(NJS_ARGB *argb)
{
    Uint32 color = (Uint32)ftrc(argb->a * 255.0F + 0.5F) << 24;

    color |= (Uint32)ftrc(argb->r * 255.0F + 0.5F) << 16;
    color |= (Uint32)ftrc(argb->g * 255.0F + 0.5F) << 8;
    return color | (Uint32)ftrc(argb->b * 255.0F + 0.5F);
}

/* from the last byte down. count must be positive: 0 runs 2^32 bytes down
 * from mem, as math.src's DT does */
void fill_bytes(void *mem, int value, int count)
{
    Uint8 *at = (Uint8 *)mem + count;
    Uint32 left = (Uint32)count;

    do {
        *--at = (Uint8)value;
    } while (--left != 0);
}

/* eight longs a pass, from the last down. size must be a positive multiple
 * of 32, and mem a multiple of 4 */
void fill_blocks(void *mem, Uint32 value, int size)
{
    Uint32 *at = (Uint32 *)((Uint8 *)mem + size);
    Uint32 passes = (Uint32)(size >> 5);

    do {
        at -= 8;
        at[7] = value;
        at[6] = value;
        at[5] = value;
        at[4] = value;
        at[3] = value;
        at[2] = value;
        at[1] = value;
        at[0] = value;
    } while (--passes != 0);
}

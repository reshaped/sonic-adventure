/* the angle from the x axis to (x, y), from -HALF to HALF, or 0x80000000
 * where both are 0. the octant is 4 where x <= 0, 2 more where y <= 0, and
 * 1 more where |y| >= |x|, as math.src's ?octants order them */
Angle angle_arc_tan2(Float y, Float x)
{
    Sint32 octant = 0;
    Float ratio;
    Float step;
    Sint32 entry;
    Sint32 angle;

    if (y == 0.0F && x == 0.0F) {
        return (Angle)0x80000000;
    }
    if (!(x > 0.0F)) {
        x = __builtin_fabsf(x);
        octant = 4;
    }
    if (!(y > 0.0F)) {
        y = __builtin_fabsf(y);
        octant += 2;
    }
    if (x > y) {
        ratio = y / x;
    } else {
        ratio = x / y;
        octant += 1;
    }
    step = 512.0F * ratio;
    entry = ftrc(step);
    step -= (Float)entry;
    angle = atan_table[entry];
    angle += ftrc((Float)(atan_table[entry + 1] - angle) * step + 0.5F);
    switch (octant) {
    case 0:
        return angle;
    case 1:
        return QUARTER - angle;
    case 2:
        return -angle;
    case 3:
        return angle - QUARTER;
    case 4:
        return HALF - angle;
    case 5:
        return QUARTER + angle;
    case 6:
        return angle - HALF;
    default:
        return -QUARTER - angle;
    }
}

/* z is written first, so out may be pos */
void point_project_centered(NJS_POINT3 *pos, NJS_POINT3 *out)
{
    Float z = pos->z;
    Float scale;
    Float x;
    Float y;

    out->z = z;
    scale = _nj_screen_.dist / z;
    x = pos->x;
    y = pos->y;
    out->y = _nj_scr_aspect_y_ * scale * y;
    out->x = _nj_scr_aspect_x_ * scale * x;
}

Float float_mod(Float x, Float y)
{
    if (y == 0.0F) {
        return 0.0F;
    }
    return x - (Float)ftrc(x / y) * y;
}

